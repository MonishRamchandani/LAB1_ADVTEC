-- Q11
SELECT s.ST_ID, s.ST_NAME, s.ST_SURNAME,
       ROUND(AVG(g.G_GRADE), 1) AS AVG_ROUND_TENTH,
       FLOOR(AVG(g.G_GRADE))    AS AVG_SMALLER_INTEGER,
       CEIL(AVG(g.G_GRADE))     AS AVG_GREATER_INTEGER
FROM STUDENTS s
JOIN GRADES g ON s.ST_ID = g.G_STUDENT
GROUP BY s.ST_ID, s.ST_NAME, s.ST_SURNAME;   

-- Q12
