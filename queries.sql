JOIN TEACHERS t ON c.C_TEACHER = t.T_ID
JOIN STUDENTS s ON g.G_STUDENT = s.ST_ID
WHERE g.G_GRADE >= 4 
  AND s.ST_ID_NUM = '081RDB141';   

